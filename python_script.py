def get_property_by_apn(apn: str):
    """
    Query the Placer STR permit API by APN and return the parsed JSON.
    """
    # 1) Construct the URL
    base = "https://str-registration-api.deckard.com/ca-placer/apn"
    # Make sure APN is URL-safe (no spaces, etc.)
    url = f"{base}/{apn}"

    # 2) Build headers
    headers = {
        "Accept": "application/json",
        # If you need to mimic the browser more closely, you could add:
        # "User-Agent": "your-app-name/1.0", 
        # "Origin": "https://placer-ca-str-permit.deckard.com"
    }

    # 3) Send the GET request
    resp = requests.get(url, headers=headers)
    resp.raise_for_status()          # crash on HTTP errors

    # 4) Parse JSON response
    return resp.json()


